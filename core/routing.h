/*
 * routing.h — Redis-compatible key → slot → shard mapping.
 *
 * Uses CRC16 (CCITT) mod 16384, identical to Redis Cluster.
 * Supports hash tags: if key contains "{...}" with non-empty content
 * between braces, only that substring is hashed.
 *
 * Slot-to-shard mapping matches the CLUSTER SLOTS response:
 *   slot_start(sid) = (16384 * sid) / num_shards
 *   slot_end(sid)   = (16384 * (sid + 1)) / num_shards - 1
 *   shard_for_slot  = slot * num_shards / 16384
 */

