static inline uint16_t routing_crc16(const char *buf, size_t len) {
  uint16_t crc = 0;
  for (size_t i = 0; i < len; i++)
    crc = (uint16_t)((crc << 8) ^
                     crc16_tab[((crc >> 8) ^ (uint8_t)buf[i]) & 0xff]);
  return crc;
}

/*
 * slot_for_key — compute Redis cluster slot for a key.
 *
 * Handles hash tags: if key contains "{...}" with non-empty content,
 * only the content between the first '{' and the next '}' is hashed.
 * This allows co-locating related keys on the same shard.
 */
static inline uint16_t slot_for_key(const char *key, size_t klen) {
  const char *s = (const char *)memchr(key, '{', klen);
  if (s) {
    const char *e =
        (const char *)memchr(s + 1, '}', klen - (size_t)(s - key) - 1);
    if (e && e > s + 1) {
      s++;
      return (uint16_t)(routing_crc16(s, (size_t)(e - s)) % 16384);
    }
  }
  return (uint16_t)(routing_crc16(key, klen) % 16384);
}

/*
 * shard_for_slot — map slot to shard id.
 *
 * Must be consistent with CLUSTER SLOTS response:
 *   slot_start(sid) = (16384 * sid) / num_shards
 * So: shard_id = slot * num_shards / 16384
 */
static inline uint32_t shard_for_slot(uint16_t slot, uint32_t num_shards) {
  return (uint32_t)((uint64_t)slot * num_shards / 16384);
}

/*
 * shard_for_key — convenience: key → shard_id in one call.
 */
static inline uint32_t shard_for_key(const char *key, size_t klen,
                                     uint32_t num_shards) {
  return shard_for_slot(slot_for_key(key, klen), num_shards);
}

